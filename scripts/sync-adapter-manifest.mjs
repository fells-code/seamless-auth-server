// Writes the adapter manifest the auth API publishes into core as its bundled
// fallback. Adapters fetch the live manifest at startup and only use this copy
// when that fails, so it only has to be as new as the oldest API it supports.
//
//   node scripts/sync-adapter-manifest.mjs [path-or-url]
//
// Defaults to the manifest on the auth API's main branch.
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const DEFAULT_SOURCE =
  "https://raw.githubusercontent.com/fells-code/seamless-auth-api/main/adapter-manifest.json";
const TARGET = join(
  import.meta.dirname,
  "../packages/core/src/manifest/bundledManifest.ts",
);

async function read(source) {
  if (!/^https?:\/\//.test(source)) {
    return readFile(source, "utf8");
  }

  const response = await fetch(source);
  if (!response.ok) {
    throw new Error(`Could not read ${source}: HTTP ${response.status}`);
  }
  return response.text();
}

const source = process.argv[2] ?? DEFAULT_SOURCE;
const manifest = JSON.parse(await read(source));

if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.routes)) {
  throw new Error(`${source} is not a schemaVersion 1 adapter manifest.`);
}

await writeFile(
  TARGET,
  `// Generated by scripts/sync-adapter-manifest.mjs. Do not edit by hand.
import type { AdapterManifest } from "./adapterManifest.js";

export const BUNDLED_ADAPTER_MANIFEST: AdapterManifest = ${JSON.stringify(manifest, null, 2)};
`,
);

console.log(
  `Wrote ${manifest.routes.length} routes (API ${manifest.apiVersion}) to ${TARGET}.`,
);
